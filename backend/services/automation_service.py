def get_test_case(
    db: Session,
    test_case_db_id: int
):

    return (
        db.query(TestCaseDB)
        .filter(
            TestCaseDB.id ==
            test_case_db_id
        )
        .first()
    )


def get_automation_for_test_case(
    db: Session,
    test_case_db_id: int
):

    return (
        db.query(AutomationScriptDB)
        .filter(
            AutomationScriptDB.test_case_db_id
            == test_case_db_id
        )
        .order_by(
            AutomationScriptDB.version.desc(),
            AutomationScriptDB.id.desc()
        )
        .first()
    )
def get_ready_automation_for_test_case(
    db: Session,
    test_case_db_id: int
):

    return (
        db.query(AutomationScriptDB)
        .filter(
            AutomationScriptDB.test_case_db_id
            == test_case_db_id,
            AutomationScriptDB.status
            == "ready"
        )
        .order_by(
            AutomationScriptDB.version.desc(),
            AutomationScriptDB.id.desc()
        )
        .first()
    )

def get_automation_history_for_test_case(
    db: Session,
    test_case_db_id: int
):

    return (
        db.query(
            AutomationScriptDB
        )
        .filter(
            AutomationScriptDB
            .test_case_db_id ==
            test_case_db_id
        )
        .order_by(
            AutomationScriptDB
            .version.desc(),
            AutomationScriptDB
            .id.desc()
        )
        .all()
    )

def get_next_automation_version(
    db: Session,
    test_case_db_id: int
) -> int:

    latest = (
        db.query(AutomationScriptDB)
        .filter(
            AutomationScriptDB.test_case_db_id
            == test_case_db_id
        )
        .order_by(
            AutomationScriptDB.version.desc(),
            AutomationScriptDB.id.desc()
        )
        .first()
    )


    if latest is None:
        return 1


    return (
        latest.version + 1
    )


def get_project_automation_scripts(
    db: Session,
    requirement_db_ids: list[int]
):

    if not requirement_db_ids:
        return []

    return (
        db.query(AutomationScriptDB)
        .join(
            TestCaseDB,
            AutomationScriptDB.test_case_db_id
            == TestCaseDB.id
        )
        .filter(
            TestCaseDB.requirement_db_id.in_(
                requirement_db_ids
            )
        )
        .order_by(
            AutomationScriptDB.id.asc()
        )
        .all()
    )

def save_real_generated_automation(
    db: Session,
    test_case_db_id: int,
    generated,
    input_schema
):

    parent = (
        get_automation_for_test_case(
            db,
            test_case_db_id
        )
    )


    new_version = (
        get_next_automation_version(
            db,
            test_case_db_id
        )
    )


    generated_engine = str(
        generated.framework or ""
    ).strip().lower()


    generated_language = str(
        generated.language or ""
    ).strip().lower()


    automation = AutomationScriptDB(
        test_case_db_id=(
            test_case_db_id
        ),

        framework=(
            generated_engine
        ),

        engine=(
            generated_engine
        ),

        language=(
            generated_language
        ),

        code=(
            generated.code
        ),

        status="draft",

        version=(
            new_version
        ),

        input_schema=(
            input_schema.model_dump()
        ),

        source="ai_generated",

        parent_version_id=(
            parent.id
            if parent
            else None
        ),

        change_summary=(
            "Generated by QualiAgent AI"
        ),
    )

    try:

        db.add(
            automation
        )


        db.commit()


        db.refresh(
            automation
        )


        return automation


    except Exception:

        db.rollback()

        raise
    
class AutomationReviewError(
    ValueError
):
    pass

def review_automation(
    db: Session,
    automation: AutomationScriptDB,
    requested_status: str
):

    current_status = str(
        automation.status or ""
    ).strip().lower()


    requested_status = str(
        requested_status or ""
    ).strip().lower()


    if requested_status not in {
        "ready",
        "rejected",
    }:

        raise AutomationReviewError(
            "Automation review status "
            "must be ready or rejected"
        )


    if current_status != "draft":

        raise AutomationReviewError(
            "Only DRAFT automation can "
            "be reviewed"
        )


    test_case = (
        db.query(TestCaseDB)
        .filter(
            TestCaseDB.id ==
            automation.test_case_db_id
        )
        .first()
    )


    if test_case is None:

        raise AutomationReviewError(
            "Parent Test Case not found"
        )


    now = datetime.utcnow()


    if requested_status == "ready":

        test_case_review_status = str(
            test_case.review_status or ""
        ).strip().lower()


        if (
            test_case_review_status !=
            "approved"
        ):

            raise AutomationReviewError(
                "Parent Test Case must remain "
                "approved before automation "
                "can become READY"
            )


        execution_type = str(
            test_case.execution_type or
            "manual"
        ).strip().lower()


        if execution_type not in {
            "automation",
            "both",
        }:

            raise AutomationReviewError(
                "Parent Test Case must be "
                "classified as AUTOMATION "
                "or BOTH before automation "
                "can become READY"
            )


        if not (
            automation.code and
            automation.code.strip()
        ):

            raise AutomationReviewError(
                "Automation code is required "
                "before approval"
            )


        if not automation.input_schema:

            raise AutomationReviewError(
                "Automation input schema "
                "is required before approval"
            )


        previous_ready_versions = (
            db.query(
                AutomationScriptDB
            )
            .filter(
                AutomationScriptDB
                .test_case_db_id ==
                automation.test_case_db_id,

                AutomationScriptDB.status
                == "ready",

                AutomationScriptDB.id
                != automation.id
            )
            .all()
        )


        for previous in (
            previous_ready_versions
        ):

            previous.status = (
                "superseded"
            )

            previous.updated_at = (
                now
            )


        automation.status = "ready"

        automation.reviewed_at = (
            now
        )

        automation.updated_at = (
            now
        )


    else:

        automation.status = (
            "rejected"
        )

        automation.reviewed_at = (
            now
        )

        automation.updated_at = (
            now
        )


    try:

        db.commit()

        db.refresh(
            automation
        )

        return automation


    except Exception:

        db.rollback()

        raise

def create_human_edited_automation_version(
    db: Session,
    source_automation: AutomationScriptDB,
    request: AutomationHumanEditRequest
):

    if source_automation is None:

        raise AutomationReviewError(
            "Source automation version "
            "was not found"
        )


    source_status = str(
        source_automation.status or ""
    ).strip().lower()


    if source_status not in {
        "ready",
        "draft",
        "rejected",
        "superseded",
    }:

        raise AutomationReviewError(
            "Source automation version "
            "has an invalid status"
        )


    if not (
        source_automation.input_schema
    ):

        raise AutomationReviewError(
            "Source automation version "
            "does not contain a persisted "
            "input schema"
        )


    if not (
        source_automation.code and
        source_automation.code.strip()
    ):

        raise AutomationReviewError(
            "Source automation version "
            "does not contain code"
        )


    next_version = (
        get_next_automation_version(
            db,
            source_automation
            .test_case_db_id
        )
    )


    new_automation = (
        AutomationScriptDB(

            test_case_db_id=(
                source_automation
                .test_case_db_id
            ),

            framework=(
                source_automation
                .framework
            ),

            engine=(
                source_automation
                .engine
                or
                source_automation
                .framework
            ),

            language=(
                source_automation
                .language
            ),

            code=(
                request.code
            ),

            status="draft",

            version=(
                next_version
            ),

            input_schema=(
                deepcopy(
                    source_automation
                    .input_schema
                )
            ),

            source="human_edited",

            change_summary=(
                request.change_summary
            ),

            parent_version_id=(
                source_automation.id
            ),
        )
    )


    try:

        db.add(
            new_automation
        )

        db.commit()

        db.refresh(
            new_automation
        )

        return new_automation


    except Exception:

        db.rollback()

        raise

